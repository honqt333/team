// Page resolution.
//
// PERFORMANCE — why this is an explicit manifest and not
// `import.meta.glob('./Pages/**/*.vue')`:
//
// A glob makes Vite enumerate every page at build time and attach a
// `__vite__mapDeps([...])` dependency list to each entry. The browser then
// fetches every one of those dependencies the moment the map is touched.
//
// Measured on the public landing page: 362 requests and ~2.1 MB transferred,
// including TenantHealthScore, Payments, Proforma, PrintEngine and the whole
// Website CMS — none of which a landing-page visitor ever opens.
//
// `pageManifest` (generated by scripts/generate-page-manifest.mjs) gives the
// same lazy per-page loading without the dependency fan-out: only the page
// that is actually requested is fetched.
//
// The trade-off: a typo in an Inertia component name now fails at runtime
// instead of at build time. `npm run build` regenerates the manifest, so a
// renamed or added page is picked up on the next build.
import { pageManifest } from './Pages/page-manifest';

function resolvePage(name) {
    const loader = pageManifest[name];
    if (!loader) {
        throw new Error(
            `Page not found: ${name}. Check that the Inertia component name matches a file under resources/js/Pages/.`
        );
    }
    return loader();
}

createInertiaApp({
    title: (title) => `${title} - ${appName}`,
    resolve: resolvePage,
    setup({ el, App, props, plugin }) {
        // Public pages can choose a locale independently from the authenticated
        // application. Sync vue-i18n before the first render so the portal never
        // shows an Arabic direction/toggle with English copy (or the reverse).
        const requestedLocale = props.initialPage?.props?.locale;
        const localeCode =
            typeof requestedLocale === 'object' ? requestedLocale?.current : requestedLocale;

        if (['ar', 'en'].includes(localeCode)) {
            i18n.global.locale.value = localeCode;
        }

        return (
            createApp({ render: () => h(App, props) })
                .use(plugin)
                .use(ZiggyVue)
                .use(i18n)
                .use(ArabicNumeralsPlugin)
                .use(SafeHtmlPlugin)
                .use(VueTelInput, {
                    defaultCountry: 'SA',
                    mode: 'international',
                    inputOptions: {
                        showDialCode: true,
                        placeholder: '5xxxxxxxx',
                        maxlength: 15,
                    },
                    validCharactersOnly: true, // Only allow numbers
                    dropdownOptions: {
                        showFlags: true,
                        showDialCodeInList: true,
                        showSearchBox: true,
                        width: '390px', // Wider dropdown for better visibility
                    },
                })
                // Design System — global App component registration
                // (Track A Phase 1). Pages can use <AppButton>, <AppInput>, etc.
                .component('AppButton', AppButton)
                .component('AppInput', AppInput)
                .component('AppSelect', AppSelect)
                .component('AppTextarea', AppTextarea)
                .component('AppCheckbox', AppCheckbox)
                .mount(el)
        );
    },
    progress: {
        color: '#4B5563',
    },
});
